/* global console, process */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const packsRoot = resolve(root, 'capability-packs');
const output = resolve(root, 'packages', 'capability-registry', 'src', 'generated-manifest.ts');
const packages = existsSync(packsRoot)
  ? readdirSync(packsRoot, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => JSON.parse(readFileSync(resolve(packsRoot, entry.name, 'package.json'), 'utf8')))
      .filter((manifest) => manifest.awmCapabilityPack === true)
      .sort((left, right) => left.name.localeCompare(right.name))
  : [];
const imports = packages.map((manifest, index) => `import pack${index} from '${manifest.name}';`);
const content = [
  '// Generated by scripts/generate-capability-manifest.mjs. Do not hand-register packs here.',
  "import type { ApplicationCapabilityPack } from '@awm/capability-sdk';",
  ...imports,
  '',
  `export const generatedCapabilityPacks: readonly ApplicationCapabilityPack[] = [${packages.map((_, index) => `pack${index}`).join(', ')}];`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = readFileSync(output, 'utf8').replaceAll('\r\n', '\n');
  if (current !== content) {
    console.error('Capability manifest is stale. Run npm run capabilities:generate.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(output, content, 'utf8');
  console.log(`Generated capability manifest with ${packages.length} pack(s).`);
}
